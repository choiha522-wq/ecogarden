def distribute_existing_questions(apps, schema_editor):
    Question = apps.get_model('missions', 'QuizQuestion')
    alias = schema_editor.connection.alias
    for category in ('observation', 'microbe', 'biology'):
        rows = list(Question.objects.using(alias).filter(
            mission__category=category, mission__mission_type='quiz',
        ).order_by('order', 'pk'))
        for question in rows:
            Question.objects.using(alias).filter(pk=question.pk).update(difficulty_level=1)
        mission = apps.get_model('missions', 'Mission').objects.using(alias).filter(
            category=category, mission_type='quiz', is_active=True,
        ).order_by('pk').first()
        if mission is None and rows:
            mission = apps.get_model('missions', 'Mission').objects.using(alias).filter(
                pk=rows[0].mission_id,
            ).first()
        if mission is None:
            continue
        for band, entries in LEVEL_BANK[category].items():
            for index, (text, choices, answer, explanation) in enumerate(entries):
                Question.objects.using(alias).get_or_create(
                    mission_id=mission.pk, text=text,
                    defaults={
                        'difficulty_level': band,
                        'order': band * 10 + index,
                        'choice1': choices[0], 'choice2': choices[1],
                        'choice3': choices[2], 'choice4': choices[3],
                        'answer': answer, 'explanation': explanation,
                    },
                )


